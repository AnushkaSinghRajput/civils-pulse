import type { SeedPyq } from "./pyqs";

/**
 * Extra Prelims-style practice items so each subject hub can run a full 20Q mock.
 * Marked GENERATED_PRACTICE in seed (not official UPSC stems).
 */
type PracticeItem = {
  subjectSlug: string;
  year: number;
  topicSlug: string;
  paper: SeedPyq["paper"];
  stem: string;
  optionA: string;
  optionB: string;
  optionC: string;
  optionD: string;
  correctOption: "A" | "B" | "C" | "D";
  explanation: string;
};

const PRACTICE_SOURCE = "https://upsc.gov.in/examinations";

function pack(
  subjectSlug: string,
  topicSlug: string,
  paper: SeedPyq["paper"],
  items: Array<{
    stem: string;
    optionA: string;
    optionB: string;
    optionC: string;
    optionD: string;
    correctOption: "A" | "B" | "C" | "D";
    explanation: string;
  }>,
): PracticeItem[] {
  return items.map((item, i) => ({
    subjectSlug,
    year: 2020 + (i % 5),
    topicSlug,
    paper,
    ...item,
  }));
}

